#!/bin/sh
# SessionStart-хук: догоняет боковое дерево доски до свежего указателя
# (origin/main), пока сессия ничего не прочитала из устаревшей доски. Гард и
# само действие живут в taskctl catchup --hook: хук это тонкая обёртка, как
# quota-refresh.sh вокруг agentctl. Молчит всё, что не боковое отставшее
# дерево: основной чекаут, деревья задач на ветках, чужие проекты без доски.
command -v taskctl >/dev/null 2>&1 || exit 0
# stderr подрезается: у старого бинаря нет catchup, и «неизвестная команда» на
# каждом старте сессии это шум. Свои сообщения режим --hook пишет в stdout, и
# старт сессии они не ломают: сделанный подтяг и отказ с причиной видны сессии.
# Пустой вывод не печатается вовсе: молчаливые деревья получают пустую строку
# от утилиты, а старт сессии не должен собирать пустые строки в контекст.
out=$(taskctl catchup --hook 2>/dev/null)
[ -n "$out" ] && printf '%s\n' "$out"
exit 0
