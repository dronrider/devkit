#!/usr/bin/env python3
"""Рубеж длинных чтений: PreToolUse-хук на Read срабатывает на вызов без
limit/offset/pages по файлу длиннее порога и отвечает подсказкой вместо
содержимого (задача DK-147, цель DK-206). Короткий файл и чтение уже куском
проходят нетронутыми. Состояния у рубежа нет: решение принимает одно stat-окно
длины файла, и истории между вызовами копить нечего.

Порог выведен из распределения длин чтений, а не из головы: замер devkitctl
drain по корпусу сессий (DK-148) показал, что чтения без limit дают ~55% вызовов
Read и ~73% его объёма. Перцентили размера вывода: у чтений целиком p75 ~303
строки, у чтений куском (limit/offset) p90 ~212 строк. Порог 300 строк режет
верхний квартиль чтений целиком, те самые длинные файлы, и он выше p90 куска:
если агенту был нужен фрагмент, куска размером до 212 строк ему хватило бы, и
чтение файла длиннее 300 строк целиком почти наверняка лишнее. Короткий файл
(ниже p50 чтений целиком, ~120 строк) проходит без подсказки.

Выход 2 (блокировка с подсказкой), а не мягкое предупреждение: у PreToolUse в
claude-code нет канала «пропустить, но предупредить», выход 0 это молчаливый
пропуск, а выход 2 это единственный способ оставить подсказку в транскрипте.
Так же работает check-reread.py, и два рубежа на одном матчере Read живут рядом,
каждый своим выходом 2 со своей подсказкой.

Чтение файла целиком перед правкой (Edit/Write следом) рубежу не видно: на
PreToolUse у хука нет будущего, и кто будет звать Edit, он не знает. Контракт
поэтому прямой: подсказка летит на любое чтение целиком длинного файла, а агент
читает нужный кусок через limit/offset или ищет место грепом. Чтение 600-строчного
файла целиком перед правкой двадцати строк это и есть та дыра, которую рубеж
режет; для правки всего файла агент собирает его двумя-тремя кусками, и это
малая плата против разового вывода в десятки тысяч символов.

Режимы:
  check-longfile.py --hook [протокол]
                     хук на PreToolUse Read: JSON события на stdin, разбор
                     входа и канал ответа по имени протокола из hookio.py,
                     голый --hook это claude-code, ответ выходом 2 с подсказкой
                     на stderr
"""
import os
import sys

import hookio

# Порог в строках. Выведен из распределения длин чтений: p75 чтений целиком и
# выше p90 куска (см. шапку). Строки, а не байты: Read режет limit в строках, и
# подсказка должна звать к limit. Число строк считается сканированием байт по
# переводу строки, без декодирования: это работает с любым Encoding и быстрее
# самого вывода Read, который хук предотвращает.
LONG_LINES = 300

# Размер блока чтения при подсчёте строк. Достаточно велик, чтобы обычный файл
# прошёл за один read, и достаточно мал, чтобы ранний выход на пороге не читал
# длинный файл целиком.
CHUNK = 65536


def text_of(value):
    return value if isinstance(value, str) else ""


def is_long(path):
    """Правда ли, что в файле не меньше LONG_LINES строк. Ранний выход на
    пороге: точный счёт длинному файлу не нужен, а читать его весь ради числа
    строк накладнее решения. Возврат None значит, что файл не открыть или он
    бинарный (нуль-байт в теле), и рубить нечего: Read отдаст его как есть, а
    считать строки в картинке или PDF нет смысла."""
    try:
        f = open(path, "rb")
    except OSError:
        return None
    n = 0
    with f:
        for block in iter(lambda: f.read(CHUNK), b""):
            # Нуль-байт это надёжный признак бинарного файла: картинки, PDF и
            # скомпилированное содержат его в первых байтах. Read отдаёт их как
            # визуальный или двоичный результат, и строки там не считать.
            if b"\x00" in block:
                return None
            n += block.count(b"\n")
            if n >= LONG_LINES:
                return True
    return False


def read_call(event):
    """Параметры вызова Read. Возврат None значит, что это не Read или у него
    нет file_path, и смотреть нечего. Иначе пара (путь, уже_кусок), где
    уже_кусок правда, если стоит limit, offset или pages: это не чтение целиком,
    и рубить его не за чем."""
    ti = event.get("tool_input")
    if not isinstance(ti, dict):
        return None
    path = text_of(ti.get("file_path"))
    if not path:
        return None
    already_chunk = any(ti.get(k) for k in ("limit", "offset", "pages"))
    return path, already_chunk


def hint(path):
    return ("файл длиннее %d строк, чтение целиком съедает контекст; "
            "позови Read с limit (и offset) для нужного фрагмента, а место ищи "
            "грепом (рубеж DK-147, цель DK-206). путь: %s\n"
            % (LONG_LINES, path))


def run_hook(protocol):
    # Протокол сверяется до разбора события: опечатка в settings.json иначе
    # выключила бы рубеж насовсем. Большинство чтений проходят без подсказки, и
    # проверять протокол надо явно, как в check-reread.py.
    hookio.entry(protocol)
    try:
        event = hookio.load()
    except hookio.BadEvent:
        return 0
    call = read_call(event)
    if call is None:
        return 0
    path, already_chunk = call
    if already_chunk:
        return 0
    long = is_long(path)
    if long is not True:
        # None (не открыть, бинарный) или False (короче порога): пропускаем.
        return 0
    return hookio.reply(protocol).found(hint(path))


def main(argv):
    args = list(argv)
    if args[:1] == ["--hook"]:
        try:
            return run_hook(hookio.protocol(args[1:]))
        except hookio.Unknown as e:
            sys.stderr.write("check-longfile: %s\n" % e)
            return 2
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
