// Package accept держит разбор вида приёмки задачи по суффиксу заголовка
// строки доски (LLD DK-292, решение 3). Регулярка и чтение вида живут тут
// однажды и доступны обоим модулям утилит: taskctl ставит и печатает вид,
// а shipctl читает его для совета после выката, и каждый модуль не нёс бы
// свой разбор суффикса.
package accept

import "regexp"

// Значения вида приёмки (LLD DK-292, решение 2). Суффикс несёт только user и
// mixed: агентский вид это умолчание, и вешать пометку на четыре строки из
// пяти дорого глазами.
const (
	Agent = "agent"
	Mixed = "mixed"
	User  = "user"
)

// SufRe разбирает суффикс «[приёмка: agent|mixed|user]». Агентский вид
// суффикса не несёт, но разбор принимает его для полной круговой прогонки
// (прошлая hand-правка могла его поставить).
var SufRe = regexp.MustCompile(`\s*\[приёмка: (agent|mixed|user)\]\s*$`)

// tailRe это временные суффиксы [провал: ...] и [блок: ...], которые стоят
// после [приёмка: ...] в фиксированном порядке (LLD DK-292, решение 3).
// End-anchored SufRe их не пробивает, поэтому KindOf снимает их прежде, чем
// искать приёмку, тем же порядком, что splitTitle в taskctl: сначала хвост, и
// потом предыдущий хвост.
var tailRe = regexp.MustCompile(`\s*\[(?:провал|блок): [^|\[]*\]\s*$`)

// KindOf читает вид из заголовка строки. Без суффикса вид агентский: это
// умолчание, перевёрнутое относительно старого «при сомнениях пользовательский»
// (LLD DK-292, решение 1). Хвосты [провал: ...] и [блок: ...] снимаются до
// поиска [приёмка: ...], иначе они стоят после приёмки и регулярка,
// привязанная к концу строки, читает user-задачу с суффиксом провала или
// блокировки как агентскую.
func KindOf(title string) string {
	rest := title
	for {
		m := tailRe.FindString(rest)
		if m == "" {
			break
		}
		rest = rest[:len(rest)-len(m)]
	}
	if m := SufRe.FindStringSubmatch(rest); m != nil {
		return m[1]
	}
	return Agent
}
