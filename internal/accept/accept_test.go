package accept

import "testing"

// TestKindOf: вид читается из суффикса заголовка, без суффикса агентский.
// Хвосты провала и блокировки стоят после приёмки и не должны маскировать её.
func TestKindOf(t *testing.T) {
	cases := []struct {
		name  string
		title string
		kind  string
	}{
		{"простой заголовок", "Починка бага", Agent},
		{"с зависимостью", "Правка [после XR-001]", Agent},
		{"явный агентский", "Правка [приёмка: agent]", Agent},
		{"пользовательский", "Правка [приёмка: user]", User},
		{"смешанный", "Правка [приёмка: mixed]", Mixed},
		{"посторонние скобки", "Правка [блок: ждём]", Agent},
		{"вид и зависимость", "Правка [после XR-001] [приёмка: user]", User},
		{"user с провалом", "Правка [приёмка: user] [провал: 500]", User},
		{"user с блоком", "Правка [приёмка: user] [блок: ждём]", User},
		{"mixed с провалом", "Правка [приёмка: mixed] [провал: 500]", Mixed},
		{"mixed с блоком", "Правка [приёмка: mixed] [блок: ждём]", Mixed},
		{"все хвосты", "Правка [после XR-001] [приёмка: user] [провал: 500] [блок: ждём]", User},
		{"агентский с провалом", "Правка [провал: 500]", Agent},
		{"агентский с блоком", "Правка [блок: ждём]", Agent},
	}
	for _, c := range cases {
		if got := KindOf(c.title); got != c.kind {
			t.Errorf("%s: KindOf(%q) = %q, ожидал %q", c.name, c.title, got, c.kind)
		}
	}
}
