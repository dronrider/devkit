// Package clientdir выбирает рабочий каталог, в котором devkit поднимает
// клиента харнеса: живой REPL в окне tmux и печатный заказ claude -p.
//
// Клиент на старте обходит дерево своего рабочего каталога. Поднятый в доме
// пользователя, он заходит в Рабочий стол, Документы, Загрузки и медиатеку, а
// macOS спрашивает разрешение на каждую такую папку у ответственного процесса
// (DK-1163). Под launchd ответственным оказывается дашборд, на системном окне
// стоит его имя, и очередь этих окон подозревается в падении WindowServer.
// Поднятый без каталога вовсе, клиент наследует рабочий каталог поднявшего, а
// у службы launchd это корень файловой системы, и обход идёт по всему диску.
//
// Каталог подъёма поэтому называется явно и лежит либо в дереве проекта,
// которое клиенту и так открыто, либо в служебном пустом каталоге под домом,
// где обходить нечего. У харнеса со своим каталогом конфигурации свой дом, и
// служебный каталог заводится под ним же.
package clientdir

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Base это каталог машинных данных devkit под домом, Name имя служебного
// каталога подъёма в нём. Каталог общий на все дороги подъёма: панель остатка,
// вход клиента и служебные вызовы утилит ходят в одно и то же пустое место.
const (
	Base = ".devkit"
	Name = "client"
)

// Path это путь служебного каталога под названным домом. Каталог тут не
// заводится: путь нужен и словам отказа, где создавать нечего.
func Path(home string) string {
	return filepath.Join(home, Base, Name)
}

// Service заводит служебный каталог и отдаёт путь к нему. Дом приходит доводом
// от зовущего: у второй подписки он свой, и класть её служебный каталог под
// дом первой значило бы поднимать клиента там, где он своего конфига не
// найдёт. Пустой дом берётся у системы.
func Service(home string) (string, error) {
	if strings.TrimSpace(home) == "" {
		h, err := os.UserHomeDir()
		if err != nil {
			return "", fmt.Errorf("дом пользователя не найден (%v), служебный каталог подъёма клиента заводить негде", err)
		}
		home = h
	}
	dir := Path(home)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("служебный каталог подъёма клиента %s не заведён: %v", dir, err)
	}
	return dir, nil
}

// Check отвечает, годится ли каталог для подъёма клиента. Пустой каталог это
// не «оставить как есть», а отказ с причиной: иначе клиент уходит гулять по
// дереву того, кто его поднял. Дом тоже не годится, и назван он тут отдельно,
// потому что раньше именно он стоял запасным вариантом у всех трёх дорог.
// Пустой home эту вторую проверку снимает: зовущий дома не знает.
func Check(dir, home string) error {
	if strings.TrimSpace(dir) == "" {
		return errors.New("каталог подъёма клиента не назван: без него клиент берёт рабочий каталог поднявшего, " +
			"а у службы launchd это корень файловой системы")
	}
	if home != "" && filepath.Clean(dir) == filepath.Clean(home) {
		return fmt.Errorf("каталог подъёма клиента это дом %s: клиент обошёл бы защищённые папки macOS и поднял диалоги доступа, "+
			"поднимать надо в дереве проекта либо в %s", home, Path(home))
	}
	return nil
}

// Pick сводит выбор в одну строку: названный каталог берётся как есть, а
// пустой и дом заменяются служебным каталогом. Зовут её дороги, у которых
// запасной вариант законен (съём панели без доверенного проекта, вход
// клиента), а там, где пустой каталог это дефект зовущего, стоит Check.
func Pick(dir, home string) (string, error) {
	if Check(dir, home) == nil {
		return dir, nil
	}
	return Service(home)
}
