// Package loadfail узнаёт нагрузочное падение теста по выводу прогона.
//
// Полный прогон слияния идёт на той же машине, где живут дашборд, сессии
// агентов и соседние прогоны, и часть тестов судит по стенному времени:
// браузерный стенд успел собрать страницу к сроку, подпроцесс ответил за
// тридцать секунд, запросы разошлись по окнам в сто пятьдесят миллисекунд.
// Под нагрузкой такой тест краснеет, не тронув ни строки кода ветки, и
// слияние отбивается чужой краснотой. Отличить её от своей по диффу нельзя:
// дифф ветки пересекается с компонентом ровно так же, как при настоящей
// поломке (цель DK-1084, задача DK-1218).
//
// Признак живёт в самом выводе, и источников у него два.
//
//  1. Маркер срока. Стенное время кончилось, и это сказано словами: убитый
//     по WaitDelay подпроцесс, снятый по сроку go test, истёкший контекст.
//     Список встроенный: это формулировки go и стандартной библиотеки, они
//     одни на все проекты.
//
//  2. Собственное признание теста строкой Mark. Тест, чей исход зависит от
//     стенного времени, печатает её в свой вывод, и другого способа узнать
//     семейство нет: имя теста о замере не говорит, а перечень имён в
//     машинном конфиге разъехался бы с кодом на первой же правке (решение
//     «форма признака нагрузочного падения», DK-1218).
//
// Судится не весь вывод компонента, а блок каждого провалившегося теста:
// иначе признание одного теста прощало бы настоящую поломку соседнего, а
// ложный ноль тут опаснее ложной единицы (замечание ревью круга 1, DK-1125).
package loadfail

import "strings"

// Mark это строка, которой тест сам называет себя замером стенного времени.
// Печатается в вывод теста (t.Log у go, обычный print у python): краснота
// такого теста считается чужой независимо от пересечения диффа с
// компонентом.
const Mark = "замер стенного времени"

// deadlineMarks это формулировки, которыми go и стандартная библиотека
// говорят «стенное время кончилось». Свои сроки подпроцессов девкита
// (gitrun, works, dashboard) печатают строку про несостоявшийся ответ за
// срок, она тут же.
var deadlineMarks = []string{
	Mark,
	"WaitDelay expired",
	"test timed out after",
	"context deadline exceeded",
	"signal: killed",
	"не ответил за",
	"снят по сроку",
}

// Shaped говорит, несёт ли кусок вывода признак нагрузочного падения.
func Shaped(block string) bool {
	for _, mark := range deadlineMarks {
		if strings.Contains(block, mark) {
			return true
		}
	}
	return false
}

// failHeads это начала строк, которыми раннеры называют провалившийся тест:
// go test печатает «--- FAIL: TestName (1.23s)», python unittest «FAIL:
// test_name (module.Class)» и «ERROR: ...». По ним вывод делится на блоки
// отдельных тестов.
var failHeads = []string{"--- FAIL: ", "FAIL: ", "ERROR: "}

// failHead возвращает имя теста, если строка это голова блока провала.
// Отступ у головы значит вложенность: go test печатает подтест с отступом
// под своим родителем, и отдельным блоком он не считается. Иначе признание
// родителя не доходило бы до подтеста, чей провал его и вызвал, и весь
// компонент судился бы как своя краснота.
func failHead(line string) (string, bool) {
	for _, head := range failHeads {
		if !strings.HasPrefix(line, head) {
			continue
		}
		name := strings.TrimSpace(strings.TrimPrefix(line, head))
		if name == "" {
			continue
		}
		if i := strings.IndexByte(name, ' '); i > 0 {
			name = name[:i]
		}
		return name, true
	}
	return "", false
}

// Fail это один провалившийся тест: имя и его собственный кусок вывода.
type Fail struct {
	Name string
	Body string
	Load bool
}

// Fails делит вывод на блоки провалившихся тестов. Строки до первой головы
// в блоки не идут: там лежит общий шум раннера, и приписывать его первому
// же тесту значило бы судить по чужому.
func Fails(out string) []Fail {
	var fails []Fail
	cur := -1
	for _, line := range strings.Split(out, "\n") {
		if name, ok := failHead(line); ok {
			fails = append(fails, Fail{Name: name})
			cur = len(fails) - 1
			continue
		}
		if cur >= 0 {
			fails[cur].Body += line + "\n"
		}
	}
	for i := range fails {
		fails[i].Load = Shaped(fails[i].Name + "\n" + fails[i].Body)
	}
	return fails
}

// Load судит вывод провалившегося компонента целиком: нагрузочным он
// считается тогда, когда провалились только тесты с признаком. Второе
// значение это имена тех тестов, по которым вышел такой вердикт, для строки
// отчёта.
//
// Вывода с блоками провалов нет вовсе (упала сборка, раннера сняли до
// первого теста) - судится весь кусок: там некому признаваться поимённо, а
// маркер срока в таком выводе это ровно та же история про кончившееся
// стенное время.
func Load(out string) (bool, []string) {
	fails := Fails(out)
	if len(fails) == 0 {
		return Shaped(out), nil
	}
	var names []string
	for _, f := range fails {
		if !f.Load {
			return false, nil
		}
		names = append(names, f.Name)
	}
	return true, names
}
