func TestCommentCoverageRequiresAConclusionForEachChangedBlock(t *testing.T) {
	root, path := fixture(t)
	write(t, filepath.Join(os.Getenv("DEVKIT_HOME"), "RULES.style.md"),
		"- **STYLE-015.** Комментарий должен соответствовать коду.\n")
	base := `package sample

// Export reads feature values.
func export() string {
	// Return the prepared value.
	return "features"
}

// Use the same value for all calls.
func same() int { return 0 }

func other() int { return 0 }
`
	write(t, filepath.Join(root, "code.go"), base)
	gitT(t, root, "add", "code.go")
	gitT(t, root, "commit", "-qm", "feature source")
	changed := strings.Replace(base, `return "features"`, `return "update"`, 1)
	changed = strings.Replace(changed, "func other", "// Zero selects the default queue.\nfunc other", 1)
	write(t, filepath.Join(root, "code.go"), changed)
	write(t, filepath.Join(root, "mapper.go"), `//go:build !debug
// +build !debug

package sample

func mapDate(raw *int) *int {
	// Preserve SQL NULL. A zero date has a different meaning.
	if raw == nil { return nil }
	return raw
}
`)
	write(t, filepath.Join(root, "generated.go"), `// Code generated by test. DO NOT EDIT.
package sample
// This is copied by the generator.
var copied = 1
`)
	report := completed(t, root, path)
	rule := findTargetRule(t, &report, commentRule)
	want := []string{"code.go:3", "code.go:5", "code.go:12", "mapper.go:7"}
	if !slices.Equal(rule.Objects, want) || rule.Targets[0].Symbol != "export" {
		t.Fatalf("ожидались %v и привязка к export, получено %+v", want, rule.Targets)
	}
	rule.Files[1].Reason = "Сгенерированный Go-файл."
	summary := filepath.Join(t.TempDir(), "review.md")
	rule.Evidence = []Evidence{{Object: "STYLE-015", Result: "checked", Location: "mapper.go:7",
		Observation: "Сохранение NULL пояснено, остальные комментарии проверены."}}
	save(t, path, report)
	write(t, summary, "# Ревью\n")
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "code.go:3: нет записи в evidence")
	assertTargetCheck(t, Validate(root, path, "XR-1"), "code.go:3: нет записи в evidence")

	const heading = "### Комментарий об экспорте"
	rule.Result = "violated"
	rule.Evidence = []Evidence{
		{Object: "code.go:3", Location: "code.go:6", Result: "violated", Heading: heading,
			CommentQuote: "Export reads feature values.", Observation: "Теперь экспорт использует update.",
			Kind: "contradiction", Facts: map[string][]ReviewFact{
				"contradiction": {{Location: "code.go:6", Text: "Теперь экспорт использует update."}},
				"claim":         {{Location: "code.go:6", Quote: "Export reads feature values.", Verdict: "violated", Text: "Теперь экспорт использует update."}},
			}},
		{Object: "code.go:5", Location: "code.go:6", Result: "violated", Heading: heading,
			CommentQuote: "Return the prepared value.", Observation: "Повторяет соседний return.",
			Kind: "restatement", Facts: map[string][]ReviewFact{
				"restatement": {{Location: "code.go:6", Text: "Повторяет соседний return."}},
				"claim":       {{Location: "code.go:6", Quote: "Return the prepared value.", Verdict: "violated", Text: "Повторяет соседний return."}},
			}},
		{Object: "code.go:12", Location: "code.go:13", Result: "checked",
			CommentQuote: "Zero selects the default queue.", Observation: "Объясняет смысл возвращаемого нуля.",
			Facts: map[string][]ReviewFact{
				"purpose": {{Location: "code.go:13", Text: "Объясняет смысл возвращаемого нуля."}},
				"claim":   {{Location: "code.go:13", Quote: "Zero selects the default queue.", Value: "0", Verdict: "checked", Text: "Объясняет смысл возвращаемого нуля."}},
			}},
		{Object: "mapper.go:7", Location: "mapper.go:8", Result: "checked",
			CommentQuote: "Preserve SQL NULL.", Observation: "Вход NULL остаётся nil, отдельно от нулевой даты.",
			Facts: map[string][]ReviewFact{
				"purpose": {{Location: "mapper.go:8", Text: "Вход NULL остаётся nil, отдельно от нулевой даты."}},
				"claim": {
					{Location: "mapper.go:8", Quote: "Preserve SQL NULL.", Value: "return nil", Verdict: "checked", Text: "Сохраняется nil."},
					{Location: "mapper.go:9", Quote: "A zero date has a different meaning.", Value: "return raw", Verdict: "checked", Text: "Значение сохраняется отдельно."},
				},
			}},
	}
	save(t, path, report)
	write(t, summary, heading+"\n\nСм. `code.go:3` и `code.go:5`.\n")
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "")
	claims := rule.Evidence[3].Facts["claim"]
	rule.Evidence[3].Facts["claim"] = nil
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "нет вывода по фрагменту \"Preserve SQL NULL.\"")
	rule.Evidence[3].Facts["claim"] = claims
	confirmed := claims[0]
	claims[0].Text = "Проверено: Preserve SQL NULL. Реализация: mapper.go:8"
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "пересказ цитаты не подтверждает checked")
	claims[0] = confirmed
	claims[0].Value = "otherValue"
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "укажите в value выражение или идентификатор")
	claims[0] = confirmed
	rule.Evidence[3].CommentQuote = "Converts all dates to UTC."
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "mapper.go:7: comment_quote не найдена")
	rule.Evidence[3].CommentQuote = "Preserve SQL NULL."
	rule.Evidence[3].Location = "mapper.go:7"
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "доказательство за пределами самого комментария")
	rule.Evidence[3].Location = "mapper.go:99"
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "строка 99 отсутствует")
	rule.Evidence[3].Location = "mapper.go:8"
	save(t, path, report)
	write(t, summary, heading+"\n\nСм. `code.go:5`.\n")
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "нужна ссылка на code.go:3")
}

func TestCommentCoverageSupportsManuallyListedFiles(t *testing.T) {
	root, path := fixture(t)
	write(t, filepath.Join(os.Getenv("DEVKIT_HOME"), "RULES.style.md"),
		"- **STYLE-015.** Комментарий должен соответствовать коду.\n")
	write(t, filepath.Join(root, "config.py"), "# Keep None distinct from zero.\n# A null date has no timestamp.\nraw_date = None\n")
	report := completed(t, root, path)
	rule := findTargetRule(t, &report, commentRule)
	if len(rule.Targets) != 0 || len(rule.Files) != 1 || rule.Files[0].Path != "config.py" {
		t.Fatalf("ожидался файл без автоматических целей: %+v", rule)
	}
	const object = "config.py:1"
	rule.Objects = []string{object}
	rule.Files[0].Objects = []string{object}
	rule.Evidence = []Evidence{{Object: object, Location: "config.py:3", Result: "checked",
		CommentQuote: "Keep None distinct from zero.", Observation: "Используется None при отсутствии даты.",
		Facts: map[string][]ReviewFact{
			"purpose": {{Location: "config.py:3", Text: "Нулевое значение не обозначает отсутствующую дату."}},
			"claim": {
				{Location: "config.py:3", Quote: "Keep None distinct from zero.", Value: "None", Verdict: "checked", Text: "None используется отдельно."},
				{Location: "config.py:3", Quote: "A null date has no timestamp.", Value: "None", Verdict: "checked", Text: "Для None нет времени."},
			},
		}}}
	summary := filepath.Join(t.TempDir(), "review.md")
	write(t, summary, "# Ревью\n")
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "")

	const question = "Где проверяется, что для None нет времени?"
	rule.Result = "pending"
	entry := &rule.Evidence[0]
	entry.Result, entry.Heading, entry.Location = "pending", "### Открытая проверка", ""
	delete(entry.Facts, "purpose")
	entry.Facts["claim"][1].Verdict, entry.Facts["claim"][1].Text, entry.Facts["claim"][1].Location = "pending", question, ""
	entry.Facts["question"] = []ReviewFact{{Location: object, Text: question}}
	save(t, path, report)
	write(t, summary, entry.Heading+"\n\n`config.py:1`\n")
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "нужен открытый вопрос по фрагменту")
	write(t, summary, entry.Heading+"\n\n`config.py:1` "+question+"\n")
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "")

	entry.Facts["claim"] = entry.Facts["claim"][:1]
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "нет вывода по фрагменту \"A null date has no timestamp.\"")
}

func TestCommentCoverageDistinguishesGoSignatureFromBehavior(t *testing.T) {
	root, path := fixture(t)
	write(t, filepath.Join(os.Getenv("DEVKIT_HOME"), "RULES.style.md"),
		"- **STYLE-015.** Комментарий должен соответствовать коду.\n")
	write(t, filepath.Join(root, "export.go"), `package sample

// Export takes a License.
// Attributes (limits and so on, e.g. max_guest_users) come from feature_values.
func Export(
	license License,
) string {
	return license.UpdateObjects
}

type License struct{ UpdateObjects string }
`)
	report := completed(t, root, path)
	rule := findTargetRule(t, &report, commentRule)
	const heading = "### Источник атрибутов"
	entry := Evidence{
		Object: "export.go:3", Location: "export.go:5", Result: "checked",
		Observation: "Аудит использует сигнатуру.", CommentQuote: "come from feature_values.",
		Facts: map[string][]ReviewFact{
			"purpose": {{Location: "export.go:5", Text: "Описывает аргумент и источник данных."}},
			"claim": {
				{Location: "export.go:6", Quote: "Export takes a License.", Value: "License", Verdict: "checked", Text: "Аргумент имеет тип License."},
				{Location: "export.go:5", Quote: "Attributes (limits and so on, e.g. max_guest_users) come from feature_values.", Verdict: "checked", Text: "Источник якобы подтверждён."},
			},
		},
	}
	rule.Evidence = []Evidence{entry}
	summary := filepath.Join(t.TempDir(), "review.md")
	write(t, summary, heading+"\n\nСм. `export.go:3`.\n")
	claims := entry.Facts["claim"]
	entry.Facts["claim"] = claims[:1]
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary),
		"нет вывода по фрагменту \"Attributes (limits and so on, e.g. max_guest_users) come from feature_values.\"")

	entry.Facts["claim"] = claims
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "сигнатура не подтверждает")

	claims[1].Location = "export.go:7"
	claims[1].Value = "feature_values"
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "сигнатура не подтверждает")

	claims[1].Location, claims[1].Value, claims[1].Verdict = "export.go:8", "", "violated"
	claims[1].Text = "Экспорт читает UpdateObjects из License."
	rule.Result = "violated"
	proof := &rule.Evidence[0]
	proof.Location, proof.Result, proof.Heading, proof.Kind = "export.go:8", "violated", heading, "contradiction"
	delete(proof.Facts, "purpose")
	proof.Facts["contradiction"] = []ReviewFact{{Location: "export.go:8", Text: claims[1].Text}}
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "")
}

func TestCommentFragmentsKeepsWrappedSentencesAndCodeTogether(t *testing.T) {
	body := "Сохраняет SQL NULL. Общий конвертер не меняется,\n" +
		"чтобы сохранить результат.\n\n" +
		"- Берёт max_guest_users и др. поля из feature_values.\n" +
		"- Читает licenses.activations_limit и `x. Y`."
	want := []string{
		"Сохраняет SQL NULL.",
		"Общий конвертер не меняется, чтобы сохранить результат.",
		"Берёт max_guest_users и др. поля из feature_values.",
		"Читает licenses.activations_limit и `x. Y`.",
	}
	if got := commentFragments(body); !slices.Equal(got, want) {
		t.Fatalf("ожидались %q, получено %q", want, got)
	}
}

func TestCheckedCommentNamesSourceAndShowsUse(t *testing.T) {
	root, path := fixture(t)
	write(t, filepath.Join(root, "source.go"), `package sample
// Output comes from source_values.
func Export(id int) (int, error) {
	if signer == nil {
		return 0, errSigner
	}
	value := source_values[id]
	return value, nil
}
`)
	files, err := os.OpenRoot(root)
	if err != nil {
		t.Fatal(err)
	}
	defer files.Close()
	source := &evidenceSource{root: root, reportPath: path, files: files, cache: make(map[string][]string)}
	claim := ReviewFact{
		Quote: "Output comes from source_values.", Verdict: "checked",
		Location: "source.go:4", Value: "if signer == nil {", Text: "Without a signer the exporter returns an error.",
	}
	e := Evidence{Object: "source.go:2", Location: "source.go:4", CommentQuote: claim.Quote,
		Result: "checked", Facts: map[string][]ReviewFact{"claim": {claim}}}
	check := func(want string) {
		t.Helper()
		e.Facts["claim"][0] = claim
		assertTargetCheck(t, checkCommentEvidence(e, source, make(map[string]goCommentEvidence)), want)
	}
	check("укажите конкретный вход")
	claim.Case, claim.Via = "id=7 with signer configured", "source.go:4"
	check("строка чтения должна содержать")
	claim.Via = "source.go:7"
	check("покажите, где значение из источника")
	claim.Location, claim.Value = "source.go:8", "value"
	claim.Text = "With id=7 the lookup reads source_values[7] into value, and returns it as the result."
	check("")
}
