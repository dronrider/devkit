func TestReviewTargetsCoverGoChangesAndUnchangedAdapters(t *testing.T) {
	root, reportPath := fixture(t)
	standards := filepath.Join(os.Getenv("DEVKIT_HOME"), "RULES.architecture.md")
	write(t, standards, "- **ARCH-018.** Проверить запросы для коллекции.\n")
	write(t, filepath.Join(root, "code.go"), `package sample
func keepName() {}
func oldName() {}
func sameName() { prepare() }
func export() { repo.loadAll(ids) }
`)
	write(t, filepath.Join(root, "sqlite.go"), `package sample
func (s *sqlite) loadAll(ids []string) {
 for _, id := range ids { s.queryOne(id) }
}
func (s *sqlite) queryOne(id string) { s.db.QueryContext(ctx, id) }
`)
	write(t, filepath.Join(root, "postgres.go"), `package sample
func (p *postgres) loadAll(ids []string) { p.db.QueryContext(ctx, ids) }
`)
	write(t, filepath.Join(root, "cache.go"), `package sample
func (c *cache) loadAll(ids []string) { c.read(ids) }
`)
	gitT(t, root, "add", ".")
	gitT(t, root, "commit", "-qm", "adapters")
	write(t, filepath.Join(root, "code.go"), `package sample
// keepName changed only in documentation.
func keepName() {}
func newName() {}
func sameName() { deliver() }
func export() {
 repo.loadAll(ids)
 publish()
}
`)
	write(t, filepath.Join(root, "new.go"), "package sample\nfunc fresh() {}\n")
	write(t, filepath.Join(root, "gen.go"), "// Code generated by test. DO NOT EDIT.\npackage sample\nfunc generated() {}\n")
	if _, err := Create(root, reportPath, "XR-1", "HEAD", false); err != nil {
		t.Fatal(err)
	}
	report, err := readReport(reportPath)
	if err != nil {
		t.Fatal(err)
	}
	naming := findTargetRule(t, &report, namingRule)
	if want := []string{"code.go:4#newName", "code.go:5#sameName", "code.go:6#export", "new.go:2#fresh"}; !slices.Equal(naming.Objects, want) {
		t.Fatalf("имена: %q, ожидаются %q", naming.Objects, want)
	}
	queries := findTargetRule(t, &report, queryRule)
	if want := []string{"postgres.go:2", "sqlite.go:2"}; !slices.Equal(queries.Objects, want) || !slices.Equal(queries.Files[0].Objects, want) {
		t.Fatalf("операции: %q, файлы: %+v, ожидаются %q", queries.Objects, queries.Files, want)
	}
}

func TestReviewTargetsRejectOmissionAndUnlinkedFindings(t *testing.T) {
	root, path := fixture(t)
	write(t, filepath.Join(root, "code.go"), "package sample\nfunc fresh() {}\n")
	report := completed(t, root, path)
	naming := findTargetRule(t, &report, namingRule)
	target := naming.Targets[0]
	naming.Objects = []string{target.Object}
	naming.Reason = "Функция добавлена."
	naming.Evidence = []Evidence{
		{Object: target.Object, Check: "meaning", Result: "checked", Symbol: target.Symbol,
			Location: target.Location, Observation: "Название обещает обновление.",
			WordChecks: []WordCheck{{Word: "fresh", Meaning: "новый", Fact: "добавлена болванка",
				Location: target.Location, Result: "checked"}}},
		{Object: target.Object, Check: "result", Result: "not_applicable",
			Location: target.Location, Observation: "Возвращаемых значений нет."},
		{Object: target.Object, Check: "writes", Result: "not_applicable",
			Location: target.Location, Observation: "Тело пустое, записей нет."},
	}
	summary := filepath.Join(t.TempDir(), "review.md")
	write(t, summary, "### Вопрос\n\nСм. `code.go:2`.\n")
	check := func(want string) {
		t.Helper()
		save(t, path, report)
		assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), want)
	}
	check("")
	naming.Objects = nil
	check("обязательный объект code.go:2#fresh отсутствует в objects")
	naming.Objects = []string{target.Object}
	naming.Targets = nil
	check("перечень targets из диффа изменён")
	naming.Targets = []Target{target}
	naming.Files[0].Objects = nil
	check("обязательный объект code.go:2#fresh отсутствует в files.objects")
	validEvidence := naming.Evidence
	naming.Evidence = naming.Evidence[:1]
	save(t, path, report)
	_, err := CoverageWithNextSteps(root, path, "XR-1", summary, "")
	if err == nil || strings.Count(err.Error(), target.Object+" -> ") != 1 {
		t.Fatalf("ожидается одна строка на %s: %v", target.Object, err)
	}
	for _, step := range []string{"files.objects", "проследите возвращаемое значение до потребителя", "найдите объект записи"} {
		if !strings.Contains(err.Error(), step) {
			t.Errorf("нет следующего шага %q: %v", step, err)
		}
	}
	naming.Evidence = validEvidence
	naming.Files[0].Objects = []string{target.Object}
	naming.Evidence[0].Symbol = "other"
	check("в meaning укажите symbol")
	naming.Evidence[0].Symbol = target.Symbol
	naming.Evidence[0].WordChecks[0].Result = ""
	check("укажите result для слова")
	naming.Result, naming.Evidence[0].Result = "pending", "pending"
	check("открытая проверка без вопроса в итоге")
	naming.Evidence[0].Heading = "### Вопрос"
	check("для pending укажите недостающий факт")
	naming.Evidence[0].Kind = "contract"
	const question = "Какое назначение функции зафиксировано в контракте?"
	naming.Evidence[0].Facts = map[string][]ReviewFact{"question": {{Location: target.Location, Text: question}}}
	check("нужен вопрос из facts.question")
	write(t, summary, "### Вопрос\n\nСм. `code.go:2`.\n\n"+question+"\n")
	check("")
	next, err := CoverageWithNextSteps(root, path, "XR-1", summary, "")
	if err != nil || len(next) != 1 || !strings.Contains(next[0], target.Object+" -> ") ||
		!strings.Contains(next[0], question) {
		t.Fatalf("открытый вопрос должен попасть в одну строку при успешной сверке: %v, %v", next, err)
	}
	naming.Evidence[0].Kind = "flow"
	naming.Evidence[0].Facts["question"][0].Text = "Нужно завершить формальное доказательство соответствия имени и фактического результата/записи."
	check("в facts.question назовите недостающий факт о коде или контракте")
	naming.Evidence[0].Facts["question"][0].Text = question
	check("укажите последний подтверждённый переход")
	naming.Result, naming.Evidence[0].Result = "violated", "violated"
	naming.Evidence[0].WordChecks[0].Result = "violated"
	check("")
	next, err = CoverageWithNextSteps(root, path, "XR-1", summary, "")
	if err != nil || len(next) != 0 {
		t.Fatalf("для доказанного нарушения с итогом работы больше нет: %v, %v", next, err)
	}
	write(t, summary, "### Вопрос\n\nСм. `code.go:20`.\n")
	check("нужна ссылка на code.go:2")
	write(t, summary, "```md\n### Вопрос\n\nСм. `code.go:2`.\n```\n")
	check("заголовок \"### Вопрос\" отсутствует")
	gitT(t, root, "add", "code.go")
	gitT(t, root, "commit", "-qm", "new function")
	assertTargetCheck(t, Validate(root, path, "XR-1"), "не завершено или нарушено")
}

func TestReviewFilesWorkWithoutAGoParser(t *testing.T) {
	root, path := fixture(t)
	write(t, filepath.Join(root, "build.js"), "export function buildReport() {}\n")
	write(t, filepath.Join(root, "export.py"), "def render_pdf(invoice):\n    return pdf(invoice)\n")
	report := completed(t, root, path)
	naming := findTargetRule(t, &report, namingRule)
	if len(naming.Files) != 2 || len(naming.Targets) != 0 {
		t.Fatalf("ожидается перечень JS и Python: %+v", naming)
	}
	naming.Objects = []string{"render_pdf", "buildReport"}
	naming.Evidence = nil
	const question = "Какой формат результата обещан внешним контрактом?"
	for i, item := range []struct{ file, name string }{{"build.js", "buildReport"}, {"export.py", "render_pdf"}} {
		naming.Files[i].Objects = []string{item.name}
		for _, check := range naming.Checks {
			e := Evidence{Object: item.name, Check: check, Location: item.file + ":1",
				Result: "pending", Observation: "Нужен контракт результата", Heading: "### Результат экспорта",
				Kind: "contract", Facts: map[string][]ReviewFact{"question": {{Location: item.file + ":1", Text: question}}}}
			if check == "writes" {
				e.Result, e.Observation, e.Heading = "not_applicable", "Вход не меняется", ""
				e.Kind, e.Facts = "", nil
			}
			naming.Evidence = append(naming.Evidence, e)
		}
	}
	naming.Result = "pending"
	summary := filepath.Join(root, "review.md")
	write(t, summary, "### Результат экспорта\n\n"+question+"\n")
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "")
	const flowQuestion = "Какой тип возвращает pdf в подключаемом обработчике?"
	naming.Evidence[1].Kind = "flow"
	naming.Evidence[1].Facts["question"][0] = ReviewFact{
		Location: "export.py:2", Value: "pdf", Text: flowQuestion,
	}
	write(t, summary, "### Результат экспорта\n\n"+question+"\n\n"+flowQuestion+"\n")
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "")
	naming.Files = naming.Files[1:]
	save(t, path, report)
	assertTargetCheck(t, CheckCoverage(root, path, "XR-1", summary), "нужен вывод по всем файлам диффа")
}

func findTargetRule(t *testing.T, report *Report, id string) *Rule {
	t.Helper()
	i := slices.IndexFunc(report.Rules, func(rule Rule) bool { return rule.ID == id })
	if i < 0 {
		t.Fatalf("правило %s отсутствует", id)
	}
	return &report.Rules[i]
}

func assertTargetCheck(t *testing.T, err error, want string) {
	t.Helper()
	if (want == "" && err != nil) || (want != "" && (err == nil || !strings.Contains(err.Error(), want))) {
		t.Fatalf("ожидается %q, получено %v", want, err)
	}
}
