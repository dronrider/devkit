package sessions

import "strings"

// Роли и этапы отрезка ленты (DK-871). Поле «повод» записи реестра несёт
// команду подъёма либо доски, и роль выводится из него таблицей «команда ->
// роль», а своего поля в строке реестра не заводится (решение человека
// 2026-09-08, развилка «роль»). Роль подписывает отрезок ленты, а не строку
// списка: склейка заходов DK-430.15 не пересматривается, и подпись стоит
// разделителем внутри ленты (развилка «склейка»).

// Роли разговора задачи. Набор закрыт постановкой DK-871: груминг, исполнение,
// ревью, проверка выката, свободный чат и виток цели. Свободный чат в таблице
// команд не значится: его отрезок узнаётся по источнику «оформление» журнала
// назначений, а из повода работа не отличима от разговора.
const (
	RoleGroom  = "груминг"
	RoleDev    = "исполнение"
	RoleReview = "ревью"
	RoleCheck  = "проверка выката"
	RoleFree   = "свободный чат"
	RoleGoal   = "виток цели"
)

// RoleUnknown подписывает отрезок, из поводов которого роль не вышла: подпись
// стоит и на неизвестной роли, молчание было бы неотличимо от отсутствия
// подписи вовсе.
const RoleUnknown = "роль неясна"

// cmdRole это таблица «команда -> роль». Ключ это начало повода до слов,
// которых в таблице нет: утилиты доски пишут в повод команду с аргументами
// («taskctl move DK-1 check»), и точное сравнение роняло бы всякую строку с ID.
// Рождения сессий (startup, resume, compact) сюда не входят: их пишет хук
// старта любому подъёму, и словами хука разговор о задаче от конвейера не
// отличить; конвейер называет себя командой taskctl run, а разговор без
// работы роли не называет и подписывается неизвестной.
var cmdRole = map[string]string{
	// Этапы из словаря видов деятельности: постановка это разбор записи до
	// кода, груминг черновика и нарезка цели; вычитка едет с правкой.
	"agentctl stage постановка": RoleGroom,
	"agentctl stage разработка": RoleDev,
	"agentctl stage вычитка":    RoleDev,
	"agentctl stage доработка":  RoleDev,
	"agentctl stage слияние":    RoleDev,
	"agentctl stage выкат":      RoleDev,
	"agentctl stage ревью":      RoleReview,
	"agentctl stage проверка":   RoleCheck,
	// Виток цели называет себя ключом --goal у вердикта и замера бюджета.
	"agentctl pick --goal":   RoleGoal,
	"agentctl run --goal":    RoleGoal,
	"agentctl spend --goal":  RoleGoal,
	"agentctl budget --goal": RoleGoal,
	// Конвейер и работа над строкой: взятие в работу и его прямые следствия.
	"taskctl run":    RoleDev,
	"taskctl move":   RoleDev,
	"taskctl close":  RoleDev,
	"taskctl ask":    RoleDev,
	"taskctl fail":   RoleDev,
	"taskctl review": RoleDev,
	// Слияние и выкат ведёт конвейер, smoke закрывает проверку выката
	// (DK-275), сценарий проверки прогоняет чужая сессия этапом «проверка».
	"shipctl start":  RoleDev,
	"shipctl code":   RoleDev,
	"shipctl merge":  RoleDev,
	"shipctl ship":   RoleDev,
	"shipctl revert": RoleDev,
	"shipctl smoke":  RoleCheck,
	// Правка кода в дереве задачи: работу называет хук утилит правки.
	"правка файла": RoleDev,
}

// cmdWords это потолок слов повода, каких хватает таблице: самая длинная
// команда из трёх слов, и дальше в поводе стоят только аргументы.
const cmdWords = 3

// Role выводит роль из повода записи реестра. Совпадение ищется с начала
// повода, сперва длинное: команды таблицы до трёх слов, дальше в поводе стоят
// аргументы. Второе значение false значит, что повод ролью не говорит: повод
// «стоп со строки» и «возврат в работу» работу называют, а чем она была, нет,
// и такая запись роль отрезка не меняет.
func Role(reason string) (string, bool) {
	words := strings.Fields(reason)
	if len(words) > cmdWords {
		words = words[:cmdWords]
	}
	for n := len(words); n > 0; n-- {
		if role, ok := cmdRole[strings.Join(words[:n], " ")]; ok {
			return role, true
		}
	}
	return "", false
}

// Stage выводит этап из повода: вид деятельности у команды «agentctl stage
// <вид>» и пусто у всего прочего. Подпись отрезка называет этап рядом с ролью,
// а словарь видов остаётся у internal/stage, и слово тут читается, а не
// проверяется: неизвестный вид у подписи останется словом повода.
func Stage(reason string) string {
	rest, ok := strings.CutPrefix(reason, "agentctl stage ")
	if !ok {
		return ""
	}
	words := strings.Fields(rest)
	if len(words) == 0 {
		return ""
	}
	return words[0]
}

// RoleStage выводит подпись отрезка ленты из записей одной сессии: чем заход
// кончил, тем и подписан, потому что стык ленты закрывает заход, и подпись на
// нём говорит итог. Выигрывает свежая запись с известной ролью, записи без
// роли пропускаются: ожидания и отвязки работу не переименовывают, и заход,
// открывший ревью и ушедший в ожидание человека, остаётся ревью. У конвейера
// работу с ролью заменяет рождение taskctl run. Известной роли нет, и подпись
// выходит неизвестной: разговор без работы в реестре не назвался.
func RoleStage(recs []Bind) (role, stage string, known bool) {
	for i := len(recs) - 1; i >= 0; i-- {
		r, ok := Role(recs[i].Reason)
		if !ok {
			continue
		}
		return r, Stage(recs[i].Reason), true
	}
	return "", "", false
}

// RoleWord собирает слово подписи отрезка: роль с этапом через двоеточие,
// неизвестная роль называется словами. Одна строка на все читатели, чтобы
// лента и отрезки журнала назначений говорили об одном и том же заходе
// одинаково.
func RoleWord(role, stage string, known bool) string {
	if !known {
		return RoleUnknown
	}
	if stage != "" {
		return role + ": " + stage
	}
	return role
}
