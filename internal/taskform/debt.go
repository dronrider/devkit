package taskform

import (
	"fmt"
	"strings"
)

// Отметка долга у сдачи (DK-1356). Перевод строки в Check открывает отметку в
// разделе «Ход работы», разбор по скиллу board-debt закрывает, ворота закрытия
// держат строку, пока отметка открыта. Смысл отметки в маршруте: сдача в Check
// приходит тремя дорогами (рука исполнителя, тик сторожка, поезд выката), и
// подписать шаг разбора на каждую дорогу отдельно значило бы держать три
// списка. Точка одна, перевод в Check, и отметка стоит независимо от того, кто
// его сделал.
//
// Форма пары та же, что у отметки smoke в «Выкате»: начало строки опознаёт
// префикс, читатель берёт последнюю отметку, поэтому круг доработки после
// возврата из Check открывает новую отметку и хвост нового диффа опять виден.

// DebtOpenNote это начало строки открытой отметки долга в разделе «Ход
// работы»: «Долг: жду разбора у диффа, <дата>». Пишет её перевод в Check,
// закрывает `taskctl debt-done`.
const DebtOpenNote = "Долг: жду разбора"

// DebtDoneNote это начало строки закрытой отметки долга: «Долг: разобран,
// <итог>, <дата>». Итог называет источник: «пересечений нет» либо взятая
// строка долга, и пустой разбор от неразобранного отличим по самой строке.
const DebtDoneNote = "Долг: разобран"

// DebtHeld говорит, ждёт ли последняя сдача строки разбора долга (на входе
// текст её файла). Решает последняя отметка раздела: открытая держит, закрытая
// отпускает, отметок нет значит сдача старше отметок, и держать нечего. Читают
// её ворота закрытия, а текст отказа собирает DebtGateNote.
func DebtHeld(doc string) bool {
	held := false
	for _, ln := range sectionLines(doc, Stages) {
		t := strings.TrimPrefix(strings.TrimSpace(ln), "- ")
		switch {
		case strings.HasPrefix(t, DebtOpenNote):
			held = true
		case strings.HasPrefix(t, DebtDoneNote):
			held = false
		}
	}
	return held
}

// DebtGateNote собирает отказ ворот закрытия: хвост долга не разобран, и
// строке расти в архив нельзя, иначе вопрос уехал бы туда вместе с ней. Отказ
// называет команду закрытия, а не ссылку на правило: закрыть хвост дешевле
// одной строкой, чем поиском скилла.
func DebtGateNote(id string) string {
	return fmt.Sprintf("%s: хвост долга не разобран, последняя сдача в Check ждёт разбор по скиллу board-debt\nзакрой хвост: taskctl debt-done %s \"пересечений нет\" (либо \"взята <ID долга>\")", id, id)
}
