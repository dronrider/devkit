// TestForksFinds: сторож формы называет подстроку не по форме, повтор имени и
// строку «оставлена» при «решает: человек», а чистый перечень оставляет без
// находок.
func TestForksFinds(t *testing.T) {
	if got := ForkFinds(listDoc); len(got) != 0 {
		t.Fatalf("на чистом перечне находки: %+v", got)
	}
	doc := `# T-004

## Развилки

- «доступ»: токен положен?
  - решает: человек
  - решено вчера: положил
- «доступ»: тот же вопрос второй раз
  - решает: человек
- «поле»: как звать?
  - решает: человек
  - оставлена человеком 2026-09-06: решит исполнитель
`
	finds := ForkFinds(doc)
	if len(finds) != 3 {
		t.Fatalf("ждали три находки, вышло %d: %+v", len(finds), finds)
	}
	if !strings.Contains(finds[0].Text, "решено") || finds[0].Line != 7 {
		t.Fatalf("подстрока не по форме названа как %+v", finds[0])
	}
	if !strings.Contains(finds[1].Text, "второй раз") || finds[1].Line != 8 {
		t.Fatalf("повтор имени назван как %+v", finds[1])
	}
	if !strings.Contains(finds[2].Text, "решает: человек") {
		t.Fatalf("противоречие передачи названо как %+v", finds[2])
	}
	// Проза без слова формы находкой не считается.
	fine := "# T-005\n\n## Развилки\n\n- «а»: вопрос?\n  - решает: человек\n  - см. соседнюю задачу\n"
	if got := ForkFinds(fine); len(got) != 0 {
		t.Fatalf("проза при развилке принята за ошибку формы: %+v", got)
	}
}

// TestForksWrite: заведение кладёт голову с полями на место раздела по форме,
// занятое имя отказывает, а подстрока дописывается под свою голову, а не в
// конец перечня.
func TestForksWrite(t *testing.T) {
	doc := "# T-006\n\n## Что происходит\n\nтекст\n\n## DoD\n\nконец\n"
	got, err := AddFork(doc, "доступ", "токен положен?", ForkHuman, "считать приватным")
	if err != nil {
		t.Fatal(err)
	}
	want := "# T-006\n\n## Что происходит\n\nтекст\n\n## Развилки\n\n- «доступ»: токен положен?\n  - решает: человек\n  - рекомендация: считать приватным\n\n## DoD\n\nконец\n"
	if got != want {
		t.Fatalf("раздел встал не по форме:\n%s", got)
	}
	if _, err := AddFork(got, "доступ", "второй раз", ForkHuman, ""); err == nil {
		t.Fatal("занятое имя завелось второй раз")
	} else if !strings.Contains(err.Error(), "доступ") {
		t.Fatalf("отказ не назвал имени: %v", err)
	}
	if _, err := AddFork(got, "поле", "как звать?", "кто угодно", ""); err == nil {
		t.Fatal("чужое значение поля «решает» принято")
	}

	got, err = AddFork(got, "поле", "как звать?", ForkExecutor, "")
	if err != nil {
		t.Fatal(err)
	}
	got, err = AppendToFork(got, "доступ", ForkDecisionLine(ByHuman, "2026-09-06", "положил в secretctl"))
	if err != nil {
		t.Fatal(err)
	}
	forks := ParseForks(got)
	if len(forks) != 2 || !forks[0].Decided() || forks[1].Decided() {
		t.Fatalf("решение легло не под свою голову:\n%s", got)
	}
	if forks[1].Name != "поле" || forks[1].State() != StateLeft {
		t.Fatalf("вторая развилка разобрана как %+v", forks[1])
	}
	if _, err := AppendToFork(got, "нет такой", "  - решено человеком 2026-09-06: ответ"); err == nil {
		t.Fatal("ответ закрыл незаведённую развилку")
	}
	// Передача исполнителю дописывает след, а состояние правит поле «решает».
	got, err = AppendToFork(got, "доступ", ForkLeaveLine(ByAgent, "2026-09-06", ""))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "оставлена агентом 2026-09-06\n") {
		t.Fatalf("след передачи без причины не записан:\n%s", got)
	}
}

// TestHoldingForks: отбор ворот (DK-804). Держит старт только открытая
// человеческая развилка: решённая отпускает, оставленная исполнителю не держала
// никогда, а перечень без единой открытой отдаётся пустым, и звать ворота на
// нём не на чем.
func TestHoldingForks(t *testing.T) {
	doc := "# T-007\n\n## Развилки\n\n" +
		"- «доступ»: токен положен?\n  - решает: человек\n  - рекомендация: считать приватным\n" +
		"- «поле»: как звать поле?\n  - решает: исполнитель\n  - рекомендация: «решает»\n" +
		"- «хранение»: раздел или команда?\n  - решает: человек\n  - решено человеком 2026-09-06: команда\n" +
		"\n## DoD\n\nконец\n"
	held := HoldingForks(doc)
	if len(held) != 1 || held[0].Name != "доступ" {
		t.Fatalf("ворота держит не та развилка: %+v", held)
	}
	if got := HoldingForks("# T-008\n\n## DoD\n\nбез перечня\n"); len(got) != 0 {
		t.Fatalf("файл без перечня развилок держит старт: %+v", got)
	}
	// Ответ снимает последнюю открытую, и ворота молчат.
	closed, err := AppendToFork(doc, "доступ", ForkDecisionLine(ByHuman, "2026-09-06", "положил в secretctl"))
	if err != nil {
		t.Fatal(err)
	}
	if got := HoldingForks(closed); len(got) != 0 {
		t.Fatalf("решённая развилка держит старт: %+v", got)
	}
}

// TestForkGateNote: отказ ворот называет имя развилки, её вопрос, рекомендацию
// и обе команды, которыми он снимается. Без них отказ говорит «нельзя» и
// молчит о том, чем это чинится.
func TestForkGateNote(t *testing.T) {
	doc := "## Развилки\n\n- «доступ»: токен положен?\n  - решает: человек\n  - рекомендация: считать приватным\n"
	note := ForkGateNote("XR-005", "старт задачи", HoldingForks(doc))
	for _, want := range []string{"XR-005", "старт задачи", "«доступ»", "токен положен?",
		"рекомендация: считать приватным", "taskctl decide XR-005 «доступ» --by человек", "--leave"} {
		if !strings.Contains(note, want) {
			t.Fatalf("в отказе нет %q:\n%s", want, note)
		}
	}
	if got := ForkGateNote("XR-005", "старт задачи", nil); got != "" {
		t.Fatalf("пустой перечень дал отказ: %q", got)
	}
}

// TestForkOptions: варианты ответа лежат подстрокой «вариант:», по строке на
// вариант (DK-864). Разбор держит их порядок, заведение пишет их следом за
// рекомендацией, а нумерация в чате начинается с рекомендации: она уже лежит
// своей подстрокой, и второй копии того же текста в записи не заводится.
func TestForkOptions(t *testing.T) {
	doc := "# T-007\n\n## Что происходит\n\nтекст\n"
	got, err := AddFork(doc, "печать", "кто собирает текст?", ForkHuman,
		"утилита печатает блок", "агент по шаблону скилла", "готовый файл")
	if err != nil {
		t.Fatal(err)
	}
	want := "- «печать»: кто собирает текст?\n  - решает: человек\n  - рекомендация: утилита печатает блок\n" +
		"  - вариант: агент по шаблону скилла\n  - вариант: готовый файл"
	if !strings.Contains(got, want) {
		t.Fatalf("варианты записаны не по форме:\n%s", got)
	}
	f, ok := FindFork(got, "печать")
	if !ok {
		t.Fatal("развилка не нашлась")
	}
	if len(f.Options) != 2 || f.Options[0] != "агент по шаблону скилла" || f.Options[1] != "готовый файл" {
		t.Fatalf("порядок вариантов не сохранён: %+v", f.Options)
	}
	choices := f.Choices()
	if len(choices) != 3 {
		t.Fatalf("вариантов для чата %d, ждал 3: %+v", len(choices), choices)
	}
	if !choices[0].Recommended || choices[0].Text != "утилита печатает блок" {
		t.Fatalf("рекомендация не стала первым вариантом: %+v", choices[0])
	}
	if choices[1].Recommended || choices[2].Recommended {
		t.Fatalf("рекомендованных вариантов больше одного: %+v", choices)
	}

	// Развилка без рекомендации нумеруется с первого «варианта», и
	// рекомендованного среди них нет: закрыть её словами «по рекомендации»
	// нечем, и это видно самому читателю списка.
	bare := Fork{Name: "имя", Options: []string{"звать по роли"}}
	if got := bare.Choices(); len(got) != 1 || got[0].Recommended {
		t.Fatalf("развилка без рекомендации получила рекомендованный вариант: %+v", got)
	}

	// Подстрока, начатая словом формы и не подошедшая под неё, это находка
	// сторожа: «варианты: а, б» одной строкой в перечень не едут.
	bad := "# T-008\n\n## Развилки\n\n- «печать»: вопрос?\n  - решает: человек\n  - варианты: а, б\n"
	finds := ForkFinds(bad)
	if len(finds) != 1 || !strings.Contains(finds[0].Text, "вариант") {
		t.Fatalf("перечисление одной строкой прошло мимо сторожа: %+v", finds)
	}
}

// TestAddForkOptionPlace: дописанный вариант встаёт после машинных подстрок
// вопроса и раньше следов. Уйди он в конец блока, перечень читался бы как
// вариант, придуманный после передачи исполнителю.
func TestAddForkOptionPlace(t *testing.T) {
	doc := "# T-009\n\n## Что происходит\n\nтекст\n"
	got, err := AddFork(doc, "область", "любая вложенная доска или контур?", ForkHuman, "только боковая директория контура")
	if err != nil {
		t.Fatal(err)
	}
	got, err = AppendToFork(got, "область", ForkLeaveLine(ByAgent, "2026-09-09", "решает исполнитель по коду"))
	if err != nil {
		t.Fatal(err)
	}
	got, err = AddForkOption(got, "область", "правило по суффиксу пути")
	if err != nil {
		t.Fatal(err)
	}
	want := "  - рекомендация: только боковая директория контура\n  - вариант: правило по суффиксу пути\n  - оставлена агентом 2026-09-09: решает исполнитель по коду"
	if !strings.Contains(got, want) {
		t.Fatalf("вариант встал не перед следом:\n%s", got)
	}
	f, ok := FindFork(got, "область")
	if !ok || len(f.Options) != 1 || f.Options[0] != "правило по суффиксу пути" {
		t.Fatalf("дописанный вариант разобран как %+v", f)
	}
	if _, err := AddForkOption(got, "нет такой", "ответ"); err == nil {
		t.Fatal("вариант лёг в незаведённую развилку")
	}
	if _, err := AddForkOption(got, "область", "   "); err == nil {
		t.Fatal("пустой вариант принят")
	}
}
