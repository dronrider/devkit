package main

import (
	"testing"
)

// forkTaskDoc это файл задачи с перечнем развилок: одна человеческая открытая,
// одна оставленная исполнителю и одна решённая. Экрану полагается показать
// первую и промолчать про остальные, потому что ворота держит только она.
const forkTaskDoc = `# XR-002: Вторая

## Развилки

- «доступ»: токен положен в secretctl?
  - решает: человек
  - рекомендация: считать приватным
- «поле»: как звать поле?
  - решает: исполнитель
  - рекомендация: «решает»
- «хранение»: раздел или своя команда?
  - решает: человек
  - решено человеком 2026-09-06: команда

## Сценарий проверки

Агентский: прогнать тесты.
`

// TestTaskForksInRow: открытые развилки едут строкой задачи (DK-804), чтобы
// экран показал их рядом с состоянием. Отбор тот же, что у ворот старта:
// решённая и оставленная исполнителю в выдачу не идут.
func TestTaskForksInRow(t *testing.T) {
	e, c, _ := tasksEnv(t)
	goalDoc(t, e, "XR-002", forkTaskDoc)

	forks, ok := taskRowField(t, getTask(t, c, e, "XR-002"), "forks").([]any)
	if !ok || len(forks) != 1 {
		t.Fatalf("в строке не одна открытая развилка: %v", forks)
	}
	f, ok := forks[0].(map[string]any)
	if !ok {
		t.Fatalf("развилка не разобралась: %v", forks[0])
	}
	if f["name"] != "доступ" || f["question"] != "токен положен в secretctl?" ||
		f["hint"] != "считать приватным" {
		t.Fatalf("развилка приехала обрезанной: %v", f)
	}

	// У задачи без перечня поля нет вовсе: пустой список в каждой строке
	// заставил бы экран рисовать чип ни о чём.
	if got := taskRowField(t, getTask(t, c, e, "XR-001"), "forks"); got != nil {
		t.Fatalf("у задачи без развилок поле непустое: %v", got)
	}
}
