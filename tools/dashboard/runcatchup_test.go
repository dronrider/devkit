package main

import (
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// Догон записи после старта (DK-1254): ручка запуска отвечает, как только
// поднялась сессия, а статус и этап пишет уже сама сессия командой
// taskctl move несколько секунд спустя. Единственный обход клиента после
// ответа (goKeepingResult) читает доску заведомо раньше этой записи, и форма
// оставалась без шапки «сейчас» и степпера этапов до случайного повода
// (фокус окна, возврат на вкладку). Постоянного опроса на форме нет нарочно,
// ради батареи телефона.
//
// Стенд поднимает песочницу app.js, жмёт «Взять в работу» и играет за время
// ограниченного догона: запись, догнавшая в пределах потолка попыток,
// приходит на форму сама, запись, не догнавшая вовсе, останавливает догон
// потолком, а не кругом, и уход с формы снимает догон, не дожидаясь ни
// одного из двух исходов.
func TestStaticRunCatchup(t *testing.T) {
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node не найден: стенд догона записи после старта пропущен")
	}
	out, err := exec.Command(node, filepath.Join("testdata", "poc_runcatchup.mjs"),
		filepath.Join("static", "app.js")).CombinedOutput()
	if err != nil {
		t.Fatalf("догон записи после старта: %v\n%s", err, out)
	}
	t.Log(strings.TrimSpace(string(out)))
}
