"""Признание python-стенда замером стенного времени (DK-1230).

Тест, чей исход держится на стенном времени (ожидание события, срок
подпроцесса, счёт запросов в окне), краснеет под нагрузкой соседей по прогону,
не тронув ни строки кода ветки (цель DK-1084, задача DK-1218). У go-стендов
признание ставит хелпер `wallClock` из `tools/dashboard/tasks_test.go`: он
печатает `loadfail.Mark` через `t.Log`, и go test пришивает этот вывод к блоку
провалившегося теста.

У python того же приёма нет: печать в stdout идёт до итогового блока unittest
(`FAILURES`) и в блок провала не попадает, `internal/loadfail.Fails` собирает
блок из строк после головы `FAIL: `/`ERROR: `, и признание, оставшееся в
stdout, для него не существует. Признание обязано ехать текстом самого
падения, и декоратор `wall_clock` делает это за тест: ловит исключение теста
и дописывает строку MARK к его тексту, прежде чем отдать дальше. Тип
исключения при этом не сохраняется: unittest различает `FAIL`/`ERROR` только
по классу (AssertionError против прочих), а признанию годится любая голова из
двух, и `AssertionError` выбран как более частая по коду.
"""
import functools
import unittest

# Строка признания, которой тест сам называет себя замером стенного времени.
# Держится вровень с `internal/loadfail.Mark` (`internal/loadfail/loadfail.go`)
# буквально: второго источника у неё нет, расхождение ловит
# `loadmark_test.py`.
MARK = "замер стенного времени"


class WallClockFailure(AssertionError):
    """Падение стенда, признавшего себя замером стенного времени. Несёт текст
    исходного исключения плюс строку MARK, а исходное исключение остаётся
    видно цепочкой `__cause__`."""


def wall_clock(fn):
    """Декоратор теста, чей исход держится на стенном времени: ожидание
    события, срок подпроцесса. Падение обёрнутого теста признаётся строкой
    MARK в собственном тексте (см. докстринг модуля), и краснота под
    нагрузкой считается `shipctl` чужой независимо от пересечения диффа с
    компонентом. Успешный вызов декоратор не трогает."""
    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        try:
            return fn(*args, **kwargs)
        except unittest.SkipTest:
            # Пропуск теста это управляющий сигнал unittest, а не падение:
            # признание тут исказило бы исход, зелёный пропуск стал бы
            # красным нагрузочным падением (замечание ревью круга 1).
            raise
        except Exception as exc:
            raise WallClockFailure("%s\n%s" % (exc, MARK)) from exc
    return wrapper
