#!/usr/bin/env python3
"""Слова отчёта devkit: число со словом в нужном падеже и однотипное одной строкой.

Установка и доводка кладут на машину десятки однотипных файлов, и человек читает
про это сверху вниз: «установлено 8 скиллов в ~/.claude/skills: ...», а не строку
на скилл и не «скиллов 8». Падеж слова после числа в русском свой на каждую
тройку, а сказуемое меняется вместе с ним, поэтому слово приходит сюда тремя
формами, а строку собирает один код на всех, кто такой отчёт печатает: установку
(update.py), доктора (devkitctl.py) и права машинного контура (perms.py).
"""


def counted(n, forms):
    """Число со словом в нужном падеже: 1 скилл, 2 скилла, 8 скиллов.

    forms это тройка форм (один, два, пять). Одиннадцать и три его соседа идут
    по третьей форме, и это не описка счёта, а его правило: «11 скиллов» при
    «21 скилл».
    """
    one, few, many = forms
    if 11 <= n % 100 <= 14:
        word = many
    elif n % 10 == 1:
        word = one
    elif 2 <= n % 10 <= 4:
        word = few
    else:
        word = many
    return "%d %s" % (n, word)


def how_many(names, forms):
    """Сколько их словами: «6 утилит», а на одном предмете просто «утилита».

    Число при одном предмете не называют вслух («установлен скилл», а не
    «установлен 1 скилл»), и находки собираются из этого куска так же, как
    отчёт о сделанном: правило счёта в выводе одно на всех.
    """
    return forms[0] if len(names) == 1 else counted(len(names), forms)


def folded(verbs, forms, names, where, why=""):
    """Однотипное одной строкой: что сделано, сколько, куда легло и что именно.

    verbs это пара сказуемых (для одного, для многих). Один предмет числа не
    называет вовсе: «установлен скилл», а не «установлен 1 скилл». Хвост why
    идёт после места и говорит, почему работа понадобилась.

    Пустой список имён это пустая строка, а не «установлено 0 скиллов»: сказать
    там нечего, потому что ничего и не сделано. Зовущий такую строку не
    печатает, и проверка непустоты у него своя, но держаться контракт обязан и
    без неё: помощник общий, а следующий зовущий про уговор может не знать.
    """
    if not names:
        return ""
    return "%s %s в %s%s: %s" % (verbs[0] if len(names) == 1 else verbs[1],
                                 how_many(names, forms), where, why, ", ".join(names))
