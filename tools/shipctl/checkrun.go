package main

import (
	"context"
	"fmt"
	"os/exec"
	"strings"
	"time"
)

// Подъём прогона сценария после выката (DK-718). Выкат при autonomous = true
// доводит задачу до прода сам, а дальше конвейер упирался в правило
// независимости: агентскую часть сценария гоняет не автор правки, и позвать
// этого проверяющего было некому. Строка стояла в Check, держала очередь
// непроверенного выката и ждала, пока человек поднимет сессию руками.
//
// Зовёт подъём тот, кто увёл строку в Check без человека в окне, то есть сам
// выкат: merge и ship при autonomous = true. Признак тут не флаг вызова, а
// доверенный агенту конвейер: команду выката катит агент, и адресата у события
// «строка в Check» нет ни одного. Явный `--deploy` в это число не входит, он
// указание человека прямо сейчас, и человек в окне у него есть. Тем же кодом
// закрыт разлив поезда тиком сторожка: тик зовёт `ship --drain`, и подъём едет
// внутри той же команды.
//
// Механику подъёма держит дашборд: `dashboard check` поднимает ту же
// tmux-сессию task-<ID>, что и кнопка запуска на экране, только заказом
// «прогони сценарий и закрой» и ярусом проверяющего. Своей копии этой
// механики у shipctl нет намеренно: ярус, подписка и очистка чужого окружения
// живут одним местом, и вторая копия разошлась бы с первой на первой правке.

// checkRunTimeout это предел подъёма: команда спрашивает доску и вердикт, а
// потом отдаёт окно tmux, и висеть ей тут не на чем. Предел нужен на случай
// подвисшего подпроцесса: слияние к этому моменту необратимо, и держать отчёт
// заложником подъёма нельзя.
const checkRunTimeout = 3 * time.Minute

// checkRunNote поднимает прогон сценария по задачам, ушедшим в Check, и
// возвращает строки для отчёта команды, тем же приёмом, что notify():
// молчащего исхода у подъёма нет ни одного, а провал подъёма не должен прятать
// то, что выкат прошёл. Пустой ответ бывает только там, где поднимать нечего
// вовсе.
func checkRunNote(root string, ids []string) string {
	if len(ids) == 0 {
		return ""
	}
	bin, err := exec.LookPath(checkRunBin)
	if err != nil {
		return fmt.Sprintf("прогон сценария не поднят: %s не нашёлся в PATH, поднимать сессию нечем;"+
			" прогнать агентскую часть сценария (%s) и отметить `shipctl smoke %s` руками",
			checkRunBin, strings.Join(ids, ", "), ids[0])
	}
	ctx, cancel := context.WithTimeout(context.Background(), checkRunTimeout)
	defer cancel()
	args := append([]string{"check", "-C", root}, ids...)
	out, err := exec.CommandContext(ctx, bin, args...).CombinedOutput()
	text := strings.TrimSpace(string(out))
	if ctx.Err() != nil {
		return fmt.Sprintf("подъём прогона сорвал срок в %s: прогнать сценарий и отметить `shipctl smoke %s` руками",
			checkRunTimeout, ids[0])
	}
	if err != nil && text == "" {
		text = err.Error()
	}
	return text
}

// checkRunBin это утилита, поднимающая сессию прогона.
const checkRunBin = "dashboard"
