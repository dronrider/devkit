package main

import (
	"fmt"
	"regexp"
	"time"
)

// Срок строки доски живёт суффиксом заголовка «[срок: 2006-01-02]» с
// абсолютной датой. Срок не трогает ранг: порядок строк держит ранг, а срок
// группирует и подсвечивает строки в панели (DK-1464, развилка «срок-ранг»
// закрыта исполнителем). Относительный срок «за N дней до другой строки»
// отвергнут разговором 2026-09-27: контроль по сроку отдельная работа.
// Машинный вывод list --json несёт дату полем due, пустое поле значит
// «срока нет».

// dueSufRe разбирает суффикс «[срок: 2006-01-02]». На него ссылается
// splitTitle, снимая суффикс при разборе заголовка.
var dueSufRe = regexp.MustCompile(`\s*\[срок: ([0-9]{4}-[0-9]{2}-[0-9]{2})\]\s*$`)

// dueOf читает дату срока из заголовка строки, пустая строка значит «срока
// нет».
func dueOf(title string) string {
	if m := dueSufRe.FindStringSubmatch(title); m != nil {
		return m[1]
	}
	return ""
}

// dueSuffix собирает суффикс заголовка по дате срока, пустая дата суффикса
// не носит: у строки без срока пометки нет, как у агентского вида приёмки.
func dueSuffix(date string) string {
	if date == "" {
		return ""
	}
	return " [срок: " + date + "]"
}

// noDue печатает прежний срок в ответе правки, у строки без срока прочерк.
func noDue(d string) string {
	if d == "" {
		return "-"
	}
	return d
}

// parseDue проверяет значение флага --due и прочерк снятия: «-» снимает срок,
// иначе ждётся дата календаря YYYY-MM-DD. Дата обязана быть настоящей:
// 2026-02-30 в суффиксе не разбирается, и ворота правки держат это здесь, а
// не находкой линтера по доске.
func parseDue(v string) (string, error) {
	if v == "-" {
		return "", nil
	}
	if _, err := time.Parse(time.DateOnly, v); err != nil {
		return "", fmt.Errorf("--due %q не читается, жду дату YYYY-MM-DD или «-» для снятия срока", v)
	}
	return v, nil
}
